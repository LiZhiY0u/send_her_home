const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createGestures } = require('../../wechat-mini-program/lighting/gestures')
const touch = (x, y) => ({ clientX: x, clientY: y })
test('orbit drag and pinch are bounded and cancel resets the baseline', () => {
  const g = createGestures()
  g.start([touch(10, 10)]); g.move([touch(60, 40)])
  assert.notEqual(g.state.yaw, 0.6)
  g.start([touch(0, 0), touch(100, 0)]); g.move([touch(0, 0), touch(200, 0)])
  assert.equal(g.state.distance, 310)
  g.move([touch(0, 0), touch(100000, 0)]); assert.equal(g.state.distance, 280)
  g.end(); const before = { ...g.state }; g.move([touch(999, 999)])
  assert.deepEqual(g.state, before)
})
test('finger changes, coincident and invalid touches never corrupt camera', () => {
  const g = createGestures()
  g.start([touch(0, 0), touch(0, 0)]); g.move([touch(0, 0), touch(100, 0)])
  g.move([touch(0, 99999)]); g.move([touch(NaN, 1)])
  assert(Object.values(g.state).every(Number.isFinite))
  g.setView('top'); assert.equal(g.state.pitch, 0.01)
  g.setView('reset'); assert.equal(g.state.distance, 620)
})
test('WeChat Canvas x/y touches rotate and pinch, cancel prevents a jump', () => {
  const g = createGestures()
  g.start([{ identifier: 0, x: 10, y: 10 }])
  g.move([{ identifier: 0, x: 60, y: 40 }])
  assert(Math.abs(g.state.yaw - 0.2) < 1e-12)
  g.start([{ identifier: 0, x: 0, y: 0 }, { identifier: 1, x: 100, y: 0 }])
  g.move([{ identifier: 0, x: 0, y: 0 }, { identifier: 1, x: 200, y: 0 }])
  assert.equal(g.state.distance, 310)
  g.end(); const before = { ...g.state }
  g.move([{ identifier: 0, x: 999, y: 999 }]); assert.deepEqual(g.state, before)
})
