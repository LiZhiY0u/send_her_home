const {test}=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'../../wechat-mini-program')
test('home uses requested names and four matching feature cards',()=>{
 const html=fs.readFileSync(path.join(root,'pages/remote/remote.wxml'),'utf8')
 assert(html.includes('send_her_home'));assert(html.includes('>？！灯灯！？ ↗'))
 assert(html.includes('>😴 ↗'));assert(!html.includes('feature-caption'))
 assert(html.includes('>？！画画！？ ↗'))
 assert.equal((html.match(/class="feature-card /g)||[]).length,4)
 assert(!html.includes('class="motor-entry"'))
 const app=JSON.parse(fs.readFileSync(path.join(root,'app.json'),'utf8'))
 assert(app.pages.includes('pages/creator/creator'))
 assert.equal(JSON.parse(fs.readFileSync(path.join(root,'pages/remote/remote.json'),'utf8')).navigationBarTitleText,'send_her_home')
 for(const route of app.pages){
  const config=JSON.parse(fs.readFileSync(path.join(root,route+'.json'),'utf8'))
  assert.equal(config.pageOrientation,'auto',route)
 }
 assert(html.includes('class="home-control"'));assert(html.includes('class="home-features" scroll-y'))
})
test('creator has local square avatar, rainbow rim, credit and automatic orientation',()=>{
 const config=JSON.parse(fs.readFileSync(path.join(root,'pages/creator/creator.json'),'utf8'))
 const html=fs.readFileSync(path.join(root,'pages/creator/creator.wxml'),'utf8')
 const css=fs.readFileSync(path.join(root,'pages/creator/creator.wxss'),'utf8')
 assert.equal(config.pageOrientation,'auto');assert(html.includes('Designed by'))
 assert(html.includes('LiZhiY0u'));assert(html.includes('/assets/creator-avatar.jpg'))
 assert(!html.includes('THE MAKER'));assert(!html.includes('creator-divider'))
 assert(!html.includes('project-name'));assert(!html.includes('creator-note'))
 assert(css.includes('rainbow-rim'));assert(fs.existsSync(path.join(root,'assets/creator-avatar.jpg')))
})
